const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const root = path.resolve(__dirname, '..');
const context = { window: {} };
vm.createContext(context);
for (const file of ['themePresets.js', 'shareConfig.js']) {
  vm.runInContext(fs.readFileSync(path.join(root, 'js', file), 'utf8'), context, { filename: file });
}

const isObject = value => value !== null && typeof value === 'object' && !Array.isArray(value);
const isColor = value => typeof value === 'string' && /^#[0-9a-f]{6}(?:[0-9a-f]{2})?$/i.test(value);
const isDate = value => {
  if (typeof value !== 'string' || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
  const date = new Date(`${value}T00:00:00Z`);
  return !Number.isNaN(date.valueOf()) && date.toISOString().slice(0, 10) === value;
};
const optionalFields = {
  holidayFilter: value => ['all', 'public', 'vacation', 'custom'].includes(value),
  holidaySearchQuery: value => typeof value === 'string',
  viewMode: value => ['plate', 'banner'].includes(value),
  currentMonthIndex: value => Number.isInteger(value) && value >= 0 && value <= 11,
  zoom: value => typeof value === 'number' && Number.isFinite(value) && value > 0,
  isDraggingViewport: value => typeof value === 'boolean',
  isPanning: value => typeof value === 'boolean',
  dragStartX: value => typeof value === 'number' && Number.isFinite(value),
  panStartX: value => typeof value === 'number' && Number.isFinite(value),
  panStartY: value => typeof value === 'number' && Number.isFinite(value),
  scrollStartX: value => typeof value === 'number' && Number.isFinite(value),
  scrollStartY: value => typeof value === 'number' && Number.isFinite(value),
};

function validatePreset(preset) {
  if (!isObject(preset)) return ['Eintrag muss ein Objekt sein'];
  const errors = [];
  const allowed = new Set([
    ...context.window.CronoShare.calendarSettingNames, '_calendarPresetVersion',
    'holidays', ...Object.keys(optionalFields)
  ]);
  for (const key of Object.keys(preset)) {
    if (!allowed.has(key)) errors.push(`${key} (unbekanntes Feld)`);
  }
  if (preset._calendarPresetVersion !== 1) errors.push('_calendarPresetVersion (erwartet: 1)');
  errors.push(...context.window.CronoShare.validateCalendarSettings(preset));
  for (const [field, valid] of Object.entries(optionalFields)) {
    if (Object.hasOwn(preset, field) && !valid(preset[field])) errors.push(field);
  }
  if (Object.hasOwn(preset, 'holidays')) {
    if (!Array.isArray(preset.holidays)) {
      errors.push('holidays (erwartet: Array)');
    } else {
      const ids = new Set();
      preset.holidays.forEach((event, index) => {
        const prefix = `holidays[${index}]`;
        if (!isObject(event)) {
          errors.push(prefix);
          return;
        }
        if (typeof event.id !== 'string' || !event.id || ids.has(event.id)) errors.push(`${prefix}.id`);
        ids.add(event.id);
        if (typeof event.title !== 'string' || !event.title.trim()) errors.push(`${prefix}.title`);
        if (!isDate(event.start)) errors.push(`${prefix}.start`);
        if (!isDate(event.end) || (isDate(event.start) && event.end < event.start)) errors.push(`${prefix}.end`);
        if (!isColor(event.color)) errors.push(`${prefix}.color`);
        if (!['public', 'vacation', 'custom'].includes(event.type)) errors.push(`${prefix}.type`);
      });
    }
  }
  return errors;
}

function generateCatalog(directory, output, report = message => console.error(message)) {
  const catalog = [];
  const names = new Set();
  let invalid = 0;
  const files = fs.readdirSync(directory, { withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.endsWith('.json'))
    .map(entry => entry.name).sort();
  for (const file of files) {
    let entries;
    try {
      entries = JSON.parse(fs.readFileSync(path.join(directory, file), 'utf8'));
    } catch (error) {
      if (!(error instanceof SyntaxError)) throw error;
      report(`${file}: Ungültiges JSON: ${error.message}`);
      invalid++;
      continue;
    }
    if (!isObject(entries)) {
      report(`${file}: Das Wurzelelement muss ein Objekt mit benannten Vorlagen sein.`);
      invalid++;
      continue;
    }
    for (const [name, preset] of Object.entries(entries)) {
      const errors = validatePreset(preset);
      if (!name.trim()) errors.unshift('Vorlagenname ist leer');
      if (names.has(name)) errors.unshift('Vorlagenname bereits vorhanden');
      if (errors.length) {
        report(`${file} / ${JSON.stringify(name)}: ${errors.join(', ')}`);
        invalid++;
        continue;
      }
      names.add(name);
      catalog.push({ name, state: preset });
    }
  }
  const json = JSON.stringify(catalog);
  const source = `// Generated by npm run presets:generate. Do not edit.\nwindow.CronoBuiltInPresets = JSON.parse(${JSON.stringify(json)});\n`;
  fs.writeFileSync(output, source, 'utf8');
  return { count: catalog.length, invalid };
}

if (require.main === module) {
  const result = generateCatalog(path.join(root, 'presets'), path.join(root, 'js', 'builtInPresets.js'));
  console.log(`${result.count} Vorlagen erzeugt; ${result.invalid} ungültige Dateien oder Einträge übersprungen.`);
  if (result.invalid) process.exitCode = 1;
}

module.exports = { generateCatalog, validatePreset };
